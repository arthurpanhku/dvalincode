/**
 * Regenerate Formula/dvalincode.rb from a published release.
 *
 * The checksums come from the release's own SHA256SUMS.txt rather than being
 * recomputed here, so the formula pins exactly what the release workflow built
 * and attested. A release whose sums file is missing an expected archive fails
 * loudly instead of emitting a formula with a hole in it.
 *
 * Usage:
 *   node scripts/update-homebrew-formula.mjs --version 0.15.0
 *   node scripts/update-homebrew-formula.mjs --version 0.15.0 --sums ./SHA256SUMS.txt
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = 'arthurpanhku/dvalincode';
const FORMULA = path.join(ROOT, 'Formula', 'dvalincode.rb');

/** The archives the formula pins. Windows is not a Homebrew target. */
const TARGETS = [
  { key: 'macosArm', os: 'macos', arch: 'arm64' },
  { key: 'macosIntel', os: 'macos', arch: 'x64' },
  { key: 'linuxArm', os: 'linux', arch: 'arm64' },
  { key: 'linuxIntel', os: 'linux', arch: 'x64' },
];

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (!token.startsWith('--')) continue;
    args[token.slice(2)] = argv[i + 1]?.startsWith('--') ? 'true' : argv[++i];
  }
  return args;
}

function fail(message) {
  console.error(`update-homebrew-formula: ${message}`);
  process.exit(1);
}

async function loadSums(version, localPath) {
  if (localPath) return readFileSync(path.resolve(localPath), 'utf8');
  const url = `https://github.com/${REPO}/releases/download/v${version}/SHA256SUMS.txt`;
  const response = await fetch(url);
  if (!response.ok) fail(`could not fetch ${url} (HTTP ${response.status}) — is the release published?`);
  return response.text();
}

/** `<sha256>  <filename>` per line, as `shasum -a 256` writes it. */
function checksumFor(sums, filename) {
  for (const line of sums.split('\n')) {
    const [hash, name] = line.trim().split(/\s+/);
    if (name === filename && /^[0-9a-f]{64}$/.test(hash ?? '')) return hash;
  }
  return null;
}

function render(version, pins) {
  const block = (key, indent) => {
    const pin = pins[key];
    return [
      `${indent}url "${pin.url}"`,
      `${indent}sha256 "${pin.sha256}"`,
    ].join('\n');
  };

  return `# Generated by scripts/update-homebrew-formula.mjs — do not edit by hand.
#
# Homebrew never applies the macOS quarantine attribute, so an installation
# through this formula is not subject to Gatekeeper the way a browser download
# would be.
class Dvalincode < Formula
  desc "Approvable, local-first AI coding agent with a governed security scanner"
  homepage "https://github.com/${REPO}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${block('macosArm', '      ')}
    end
    on_intel do
${block('macosIntel', '      ')}
    end
  end

  on_linux do
    on_arm do
${block('linuxArm', '      ')}
    end
    on_intel do
${block('linuxIntel', '      ')}
    end
  end

  def install
    # The binary resolves its web assets as dirname(execPath)/web/dist, so it
    # has to stay next to the extracted tree. Homebrew resolves the symlink
    # when the executable starts, which keeps that lookup pointing at libexec.
    libexec.install Dir["*"]
    binary = Dir[libexec/"dvalincode-*"].find { |f| File.file?(f) && File.executable?(f) }
    odie "no dvalincode binary in the archive" if binary.nil?
    bin.install_symlink binary => "dvalincode"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/dvalincode --version")
    # Scanning needs no API key, no model, and no config — so the formula can
    # prove the install actually works rather than only that it starts.
    (testpath/"vuln.js").write("app.post('/x', (req, res) => res.send(String(eval(req.body.e))));\\n")
    output = shell_output("#{bin}/dvalincode dvalin #{testpath} --scanners builtin --json")
    assert_match "dvalin/eval", output
  end
end
`;
}

const args = parseArgs(process.argv.slice(2));
const version = (args.version ?? '').replace(/^v/, '');
if (!version) fail('pass --version <x.y.z>');

const sums = await loadSums(version, args.sums);
const pins = {};
for (const target of TARGETS) {
  const filename = `dvalincode-v${version}-${target.os}-${target.arch}.tar.gz`;
  const sha256 = checksumFor(sums, filename);
  if (!sha256) fail(`no checksum for ${filename} in SHA256SUMS.txt`);
  pins[target.key] = {
    url: `https://github.com/${REPO}/releases/download/v${version}/${filename}`,
    sha256,
  };
}

const rendered = render(version, pins);
const previous = (() => {
  try {
    return readFileSync(FORMULA, 'utf8');
  } catch {
    return '';
  }
})();

if (previous === rendered) {
  console.log(`Formula already at ${version} — nothing to do.`);
  process.exit(0);
}

writeFileSync(FORMULA, rendered, 'utf8');
console.log(`✓ Formula/dvalincode.rb → ${version}`);
for (const target of TARGETS) console.log(`  ${target.os}-${target.arch}  ${pins[target.key].sha256.slice(0, 16)}…`);
